/**
 * Returns user object with localized title and department
 */
const getLocalizedStaff = (user, lang) => {
  if (!user) return user;
  const l = lang || (typeof currentLang !== 'undefined' ? currentLang : 'vi');
  const userMap = staffTranslations[l] && staffTranslations[l][user.id];
  if (userMap) {
    return {
      ...user,
      title: userMap.title || user.title,
      department: userMap.department || user.department
    };
  }
  // Generic fallbacks based on role if custom id not found
  if (l === 'en') {
    if (user.role === 'super_admin' || user.role === 'admin') {
      return { ...user, title: user.title || "Executive Director", department: user.department || "Board of Directors" };
    } else if (user.role === 'warehouse_logistics') {
      return { ...user, title: user.title || "GSP Warehouse Pharmacist", department: user.department || "Logistics & Cold-Chain" };
    } else if (user.role === 'sales_rep') {
      return { ...user, title: user.title || "B2B Account Manager", department: user.department || "Sales & Partnerships" };
    }
  } else if (l === 'zh') {
    if (user.role === 'super_admin' || user.role === 'admin') {
      return { ...user, title: user.title || "执行董事", department: user.department || "董事会管理部" };
    } else if (user.role === 'warehouse_logistics') {
      return { ...user, title: user.title || "GSP冷链仓储药师", department: user.department || "冷链物流与品控部" };
    } else if (user.role === 'sales_rep') {
      return { ...user, title: user.title || "B2B大客户经理", department: user.department || "市场销售部" };
    }
  }
  return user;
};

