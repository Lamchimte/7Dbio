/**
 * Returns a cloned product object with localized strings applied for the active language.
 */
const getLocalizedProduct = (prod, lang) => {
  if (!prod) return prod;
  const l = lang || (typeof currentLang !== 'undefined' ? currentLang : 'vi');
  if (l === 'vi' || !productTranslations[l] || !productTranslations[l][prod.id]) {
    return prod;
  }
  const tData = productTranslations[l][prod.id];
  return {
    ...prod,
    name: tData.name || prod.name,
    description: tData.description || prod.description,
    uses: tData.uses || prod.uses,
    usage: tData.usage || prod.usage,
    medicalSpecs: {
      ...prod.medicalSpecs,
      ...(tData.specs || {})
    }
  };
};

